const TierChip = ({ f }: { f: RField }) => f.tier ? <span className={`tier ${f.tier}`} title={f.tier}>{TIER_LETTER[f.tier]}</span> : null;

function MadeInfo({ m }: { m?: Made | null }) {
  if (!m) return null;
  const rows: ReactNode[] = [];
  if (m.labeler) rows.push(`labeled by ${m.labeler.method || '?'}${m.labeler.model ? ' / ' + m.labeler.model : ''}${m.labeler.when ? ' on ' + m.labeler.when : ' (date not recorded)'}`);
  else rows.push('labeler not recorded (imported from petey-master)');
  if (m.origin) rows.push(`made in ${m.origin.repo}: first commit ${m.origin.first.when} by ${m.origin.first.who}, last ${m.origin.last.when} by ${m.origin.last.who}`);
  if (m.git_first) rows.push(`in git since ${m.git_first.when} by ${m.git_first.who} (${m.git_first.commit}: ${m.git_first.subject.slice(0, 60)})`);
  if (m.git_last && (m.git_commits || 0) > 1) rows.push(`last commit ${m.git_last.when} by ${m.git_last.who} (${m.git_last.commit}: ${m.git_last.subject.slice(0, 60)}); ${m.git_commits} commits`);
  if (m.uncommitted) rows.push(<span className="stale">uncommitted changes on disk</span>);
  if (m.file_time) rows.push(`not in git; file last written ${m.file_time}`);
  if (m.loop_edits) rows.push('loop edits kept: ' + Object.entries(m.loop_edits).map(([k, n]) => `${n} by ${k || '?'}`).join(', '));
  // the generation run (petey.validate's loop, `validate --blank`), not the passes or a hand review (2026-10-16)
  if (m.validated) rows.push(`generated by run ${m.validated.run ? m.validated.run + ' ' : ''}on ${m.validated.when || '?'}`);
  return <div className="help">{rows.map((r, i) => <Fragment key={i}>{i ? <br /> : null}{r}</Fragment>)}</div>;
}

function Head() {
  const BP = useReview(s => s.BP)!;
  // the blueprint's own metadata, folded away (2026-10-07); a stale record stays visible
  return (
    <>
      {BP.stale && <div className="stale">The verdicts predate this blueprint file.</div>}
      <details className="meta"><summary>Blueprint details</summary>
        <dl>
          <dt>File</dt><dd>{BP.path}</dd>
          <dt>Blank PDF</dt><dd>{BP.blank ? <span title={BP.blank}>{BP.blank.split('/').pop()}</span> : <i>not found</i>}</dd>
          {BP.build && <><dt>Built with</dt><dd>{BP.build.finder}</dd></>}
        </dl>
        <MadeInfo m={BP.made} />
      </details>
    </>
  );
}

// a field named in a reason (`name`) shows its id and selects that field when clicked
function FieldRefs({ text }: { text: string }) {
  const fields = useReview(s => s.BP!.fields);
  const bits = text.split(/`([a-z0-9_]+)`/g);
  return <>{bits.map((b, i) => {
    if (i % 2 === 0) return <Fragment key={i}>{b}</Fragment>;
    const g = fields.find(x => x.name === b);
    return g ? <a key={i} href="#" className="fref" onClick={e => { e.preventDefault(); select(b); }}><span className="fid">{g.id || ''}</span> <code>{b}</code></a> : <code key={i}>{b}</code>;
  })}</>;
}

function WhyQuestioned({ f }: { f: RField }) {
  const fields = useReview(s => s.BP!.fields);
  const busy = useReview(s => s.busy);
  // one plain sentence per reason (witness.explain): errors first, then suggestions (2026-10-07)
  if (!f.why || !f.why.length) return null;
  return (
    <div className="sect"><h4>Why it is questioned</h4><div className="why">{f.why.map((w, i) => (
      <div key={i} className={w.kind}>{w.kind === 'suggestion' ? 'Suggestion: ' : ''}<FieldRefs text={w.text} />
        {w.fix && <> <button className="btn usefix" onClick={() => useFix(w.fix)}
          title={w.fix.name && fields.some(x => x.name === w.fix!.name) ? `take the name ${w.fix.name}; that field keeps it until you rename it too, so the rename waits as a clash (the clashes button shows both)` : 'put this into the field above; save to keep it'}>use</button></>}
        {/^Option captions/.test(w.text) && f.options.length > 0 && !w.fix && <> <button className="btn usefix" disabled={busy.fixcaps} onClick={() => fixCaptions(f)}
          title="ask the agent for the captions printed at each box (one call, a few seconds); they fill the option boxes, and you save">{busy.fixcaps ? 'asking…' : 'fix captions'}</button></>}
      </div>))}</div></div>
  );
}

// the post-review agent's proposal for a flag with a note (flag_agent.py): "use" fills the correction boxes, or marks a
// removal; nothing is written until the person saves (2026-10-07)
function AgentBox({ v }: { v?: Verdict }) {
  const a = v?.agent; if (!a) return null;
  const opts = a.options && Object.keys(a.options).length
    ? Object.entries(a.options).map(([k, d]) => `${k}${d.key ? ' → ' + d.key : ''}${'caption' in d ? ` "${d.caption}"` : ''}`).join(', ') : '';
  const parts: ReactNode[] = [a.name && <>name → <code>{a.name}</code></>, a.type && `type → ${a.type}`, a.semantic_type && `semantic type → ${a.semantic_type}`,
    a.pattern && <>pattern → <code>{a.pattern}</code></>, a.description && `description → "${a.description}"`, opts && `options → ${opts}`].filter(Boolean);
  const what = a.action === 'edit' ? (parts.length ? parts.map((p, i) => <Fragment key={i}>{i ? ', ' : ''}{p}</Fragment>) : 'no change')
    : ({ remove: 'remove: not a field', regroup: 'part of an option group (do it in the Groups tab)', none: 'no change it can make' } as Record<string, string>)[a.action] || a.action;
  const usable = (a.action === 'edit' && (a.name || a.type || a.semantic_type || a.pattern || opts)) || a.action === 'remove';
  return (
    <div className="agent"><b>Agent proposes:</b> {what}
      {usable && <> <button className="btn" title="put this into the field above; save to keep it" onClick={() => useFix(a)}>use</button></>}
      <div className="help">{a.reason || ''} · for your note "{a.for_note || ''}"</div></div>
  );
}

const PART_HINT: Record<PartKey, string> = {
  block_prefix: 'the block it belongs to (child, employment, vehicle); empty when in none',
  block_iteration: 'which block (2 for the second child); empty when the block occurs once',
  subject: "what the box is about, in the form's own words", suffix: 'the kind of value (txt, nm, nbr, dt, amt, ind …); an option group has none',
  iteration: 'the Nth field holding this information (3, 4a, b); empty when it occurs once', part: 'which box of a value written in several boxes (month, area, dollars, 1)',
};

/** Enter saves the correction, Esc puts the boxes back (and leaves the box). */
function boxKeys(e: React.KeyboardEvent<HTMLElement>) {
  if (e.key === 'Enter') { e.preventDefault(); saveFix(); }
  else if (e.key === 'Escape') { e.preventDefault(); resetBoxes(); (e.target as HTMLElement).blur(); }
  e.stopPropagation();
}

// a correction (2026-10-07): the field's name, type, semantic type, pattern, options and parts edited in place; saved as
// an accept with a structured edit, which goes into the working copy
function FieldCard({ f, v }: { f: RField; v?: Verdict }) {
  const { boxes, idsOpen, busy, selOpt, BP } = useReview();
  if (!boxes || !BP) return null;
  const dirty = dirtyOf(), d = (k: string) => (dirty.keys.has(k) ? 'dirty' : undefined);
  // an option group answers one of / any of its boxes: only category or multi_category (Andrew, 2026-10-07)
  const types = f.options.length > 1 ? ['category', 'multi_category'] : ['string', 'number', 'integer', 'date', 'boolean', 'category', 'multi_category'];
  const dd = !f.options.length && (f.choices || []).length > 0;
  const ol = optList(f);
  const id = f.identifiers || {};
  const saved = v?.edit && !v.applied;
  return (
    <div className="fcard sect">
      <h4 id="fref" title="click to copy the field reference (file_page_n)" onClick={() => copyRef(f)}>Selected field {f.id && <code className="fid">{fieldRef(f)}</code>}<TierChip f={f} />
        <span className="help">page {f.page}{f.tier ? ' · ' + f.tier : ''}</span></h4>
      <div className="fgrid">
        <label>Field name</label>
        <span className="namerow"><input id="eName" value={boxes.name} readOnly spellCheck={false} className={d('name')} onKeyDown={boxKeys}
          title="printed from its parts (subject, suffix, iteration, part); edit the parts to change it" />
          <button className="btn parts" title="the parts the name is printed from" onClick={toggleIds}>{idsOpen ? 'parts ▾' : 'parts ▸'}</button></span>
        {idsOpen && <>
          {PART_KEYS.map(k => <Fragment key={k}><label className="sub" htmlFor={`i_${k}`}>{k}</label>
            <input className={'ipart' + (d(`p:${k}`) ? ' dirty' : '')} id={`i_${k}`} value={boxes.parts[k]} placeholder="none" spellCheck={false} title={PART_HINT[k]}
              onChange={e => setPart(k, e.target.value)} onKeyDown={boxKeys} /></Fragment>)}
          <span className="lbl sub">in</span><span>{id.grid ? <>grid <code>{id.grid}</code></> : <i>in no kept grid</i>}<span className="help"> · {f.identifiers_stored ? 'parts stored on the field' : 'parts read from the name'}</span></span>
          {(f.identifier_flags || []).length > 0 && <><span className="lbl sub">read</span><span className="stale">{f.identifier_flags!.join('; ')}</span></>}
        </>}
        <label htmlFor="eType">Type</label>
        <select id="eType" value={boxes.type} className={d('type')} onChange={e => setBox('type', e.target.value)} onKeyDown={boxKeys}>
          {!types.includes(boxes.type) && <option value={boxes.type} disabled>{boxes.type} (not allowed for a group)</option>}
          {types.map(t => <option key={t}>{t}</option>)}
        </select>
        <label htmlFor="eSem">Semantic type</label>
        <input id="eSem" list="semList" placeholder="none" value={boxes.semantic_type} spellCheck={false} className={d('semantic_type')}
          onChange={e => setBox('semantic_type', e.target.value)} onKeyDown={boxKeys} />
        <label htmlFor="ePat">Pattern</label>
        <input id="ePat" placeholder="none" value={boxes.pattern} spellCheck={false} className={d('pattern')}
          onChange={e => setBox('pattern', e.target.value)} onKeyDown={boxKeys} />
        {f.values && !(f.choices || []).length && <><span className="lbl">Values</span><span>{f.values.join(', ')}</span></>}
        <span className="lbl">Description</span><span>{f.description || <i>none</i>}</span>
        {ol.length > 0 && <>
          <span className="lbl">{dd ? 'Dropdown' : 'Options'}<br /><span className="help">key · caption</span></span>
          <span className="otable">{ol.map(o => (
            // the option row of the box clicked on the page, and the other way round: a row focused or hovered lights its box
            <span key={o.k} className={'orow' + (o.k === selOpt ? ' osel' : '')} data-k={o.k}
              onFocus={() => useReview.setState({ selOpt: o.k })} onMouseEnter={() => useReview.setState({ selOpt: o.k })}>
              <input className={'okey' + (d(`o:${o.k}:key`) ? ' dirty' : '')} value={boxes.options[o.k]?.key ?? ''} spellCheck={false}
                title={dd ? `the value extraction returns for this entry${o.stored != null ? `; the PDF stores ${o.stored}` : ''}` : 'the value extraction returns for this box'}
                onChange={e => setOpt(o.k, 'key', e.target.value)} onKeyDown={boxKeys} />
              <input className={'ocap' + (d(`o:${o.k}:caption`) ? ' dirty' : '')} value={boxes.options[o.k]?.caption ?? ''} placeholder="no caption"
                title={(dd ? 'the text shown for this entry in the list' : 'the text printed at this box') + '; empty clears it'}
                onChange={e => setOpt(o.k, 'caption', e.target.value)} onKeyDown={boxKeys} />
            </span>))}</span>
        </>}
      </div>
      <datalist id="semList">{[...(BP.semantic_types || [])].sort().map(t => <option key={t}>{t}</option>)}</datalist>
      <div className="frow">
        <button className="btn flag" id="vFix" disabled={!dirty.any} onClick={saveFix} title="save the changed boxes as a correction: it goes into the working copy and the field is accepted">save correction</button>
        <button className="btn" id="vUndo" disabled={!dirty.any} onClick={resetBoxes} title="put the boxes back as they were">undo changes</button>
        <button className="btn" id="vImprove" disabled={busy.improve} onClick={() => improveName(f)}
          title="ask the review agent for a name that says what the box holds (one call, a few seconds); it fills the name box, and you save">{busy.improve ? 'asking…' : 'improve name'}</button>
        {f.options.length > 1 && <button className="btn" id="vCaps" disabled={busy.caps} onClick={() => rereadCaptions(f)}
          title="read each box's printed caption again (one call to the review agent with the page image); captions from the PDF's form data or set by hand stay; it fills the option boxes, and you save">{busy.caps ? 'reading…' : 're-read captions'}</button>}
        {saved && <span className="help">Correction saved, held back from the working copy (a name another field has; the apply button in the bar retries); the working copy has{' '}
          <code>{f.name}</code> : {f.type || ''}{f.semantic_type ? ' / ' + f.semantic_type : ''}{f.pattern && <> / <code>{f.pattern}</code></>}{v!.edit!.options ? `; ${Object.keys(v!.edit!.options).length} option(s) changed` : ''}</span>}
      </div>
    </div>
  );
}

async function copyRef(f: RField) {
  if (!f.id) return;
  const ref = fieldRef(f);
  try { await navigator.clipboard.writeText(ref); }
  catch { const t = document.createElement('textarea'); t.value = ref; document.body.appendChild(t); t.select(); document.execCommand('copy'); t.remove(); }
  toast(`Copied ${ref}`);
}

// the field's metadata, folded away: the full widget path and what each check said
