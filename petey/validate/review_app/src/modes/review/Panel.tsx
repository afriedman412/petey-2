function FieldList() {
  const { selected, BP } = useReview();          // the whole store: the list follows its filters and order too
  return (
    <div className="rlist">{ordered().map(f => {
      const e = BP!.verdicts[f.name]?.edit;
      return (
        <div key={f.name} data-n={f.name} className={`${verdictOf(f.name)} ${f.name === selected ? 'sel' : ''} ${isRemoved(f.name) ? 'removed' : ''}`} onClick={() => select(f.name)}>
          <TierChip f={f} /><span className="fid">{f.id || 'p' + f.page}</span> · {f.name}
          {e && <b> → {e.name || f.name}{e.type ? ' : ' + e.type : ''}{e.semantic_type ? ' / ' + e.semantic_type : ''}</b>}
        </div>);
    })}</div>
  );
}

export function Panel() {
  const { BP, selected, note } = useReview();
  useReview(s => s.removed);
  const f = fieldOf(selected);
  if (!BP) return null;
  if (!f) return <div className="rpanel"><Head /><p className="help">Click a box on the page, or a field in the list below.</p><ListOrder /><FieldList /></div>;
  const v = BP.verdicts[f.name], removed = isRemoved(f.name);
  return (
    <div className="rpanel">
      <Head />
      <FieldCard key={f.name} f={f} v={v} />
      {f.claude && <div className="loop"><b>Claude's pass</b> ({f.claude.kind}){f.claude.from && f.claude.from !== f.name && <> was <code>{f.claude.from}</code></>}: {f.claude.why || ''}</div>}
      <WhyQuestioned f={f} />
      <AgentBox v={v} />
      {f.loop && <div className="loop"><b>Loop changed</b> {(f.loop.changed || []).join(', ')}{f.loop.old_name && <> (was <code>{f.loop.old_name}</code>)</>}<br />{f.loop.reason || ''}</div>}
      {f.adjudication && <div className="adj"><b>Adjudicator</b> {f.adjudication.verdict} for <code>{f.adjudication.proposed}</code>: {f.adjudication.reason || ''}</div>}
      {removed && <div className="rbanner">Recorded for removal, not removed yet (see Add / remove's change list). <button className="btn" onClick={keepField}>keep it</button></div>}
      <div className="sect"><h4>Verdict</h4><div className="verdict" style={{ marginTop: 0 }}>
        <button className={'btn accept' + (v?.verdict === 'accept' ? ' on' : '')} id="vAccept" title="the field is right; go to the next" onClick={() => setVerdict('accept')}>accept</button>
        <button className={'btn flag' + (v?.verdict === 'flag' ? ' on' : '')} id="vFlag" title="I can't or don't want to fix this myself: say what is wrong in the note (review edits sends it to the agent)" onClick={() => setVerdict('flag')}>flag</button>
        <button className="btn" id="vClear" title="no verdict" onClick={() => setVerdict(null)}>clear</button>
        {!removed && <button className="btn warn" id="vRemove" title="remove this field from the blueprint" onClick={removeField}>remove field</button>}
      </div></div>
      <div className="sect"><h4>Note</h4>
        <textarea id="note" placeholder="anything else that is wrong (saved with the verdict)" value={note}
          onChange={e => setNote(e.target.value)} onBlur={() => saveNote()}
          onKeyDown={e => { if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); saveNote(); e.currentTarget.blur(); } e.stopPropagation(); }} /></div>
      <Details f={f} />
      <ListOrder />
      <FieldList />
    </div>
  );
}

export function Bar() {
  const { BP, justChecked } = useReview();
  if (!BP) return <span className="progress" id="progress" />;
  const n = BP.fields.length, acc = BP.fields.filter(f => verdictOf(f.name) === 'accept').length, flg = BP.fields.filter(f => verdictOf(f.name) === 'flag').length;
  const t: Record<string, number> = {}; BP.fields.forEach(f => { if (f.tier) t[f.tier] = (t[f.tier] || 0) + 1; });
  const tiers = Object.keys(TIER_RANK).filter(k => t[k]).map(k => `${k} ${t[k]}`).join(' · ');
  const c = BP.checked;
  const ck = !c ? null : c.validated ? <span className="badge validated" title="every field has a verdict, none flagged, every correction applied">validated</span>
    : c.stale ? <span className="badge stalecheck">checked, file changed since</span>
    : <span className="badge checked" title={`every field has a verdict${c.flagged ? '; flags still need work' : ''}${c.pending ? '; corrections still to apply' : ''}`}>checked {(c.when || '').slice(0, 10)}{c.flagged ? `, ${c.flagged} flagged` : ''}{c.pending ? `, ${c.pending} to apply` : ''}</span>;
  const props = Object.values(BP.verdicts).filter(v => v.agent).length;
  // corrections held back from the working copy (a rename onto a name another field still has): a retry button
  const names = new Set(BP.fields.map(f => f.name));
  const pending = Object.entries(BP.verdicts).filter(([nm, v]) => v.edit && !v.applied && names.has(nm)).length;
  return (
    <span className={'progress' + (justChecked ? ' justchecked' : '')} id="progress">
      {ck}{ck ? ' ' : ''}<b>{acc}</b> accepted · <b>{flg}</b> flagged · <b>{n - acc - flg}</b> left of {n}
      {tiers && <> <span className="help">({tiers})</span></>}
      {BP.witness_error && <> <span className="stale">witnesses failed: {BP.witness_error}</span></>}
      {BP.agent_running ? <> <span className="help">· the agent is reviewing your edits…</span></> : <>
        {props > 0 && <> <span className="help">· {props} agent proposal{props === 1 ? '' : 's'}</span></>}
        {!!BP.agent_todo && <> <button className="btn" onClick={reviewEdits} title="send the fields you flagged with a note to the agent; it proposes corrections for you to use and apply">review edits ({BP.agent_todo})</button></>}
      </>}
      {pending > 0 && <> <button className="btn ok" onClick={applyCorrections} title="corrections held back by a name clash: try them again once the other field is renamed">apply {pending} held-back correction{pending === 1 ? '' : 's'}</button></>}
    </span>
  );
}
